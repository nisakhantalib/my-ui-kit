const CATALOGUES: Record<Lang, Record<SiteKey, string>> = { en, 'zh-Hant': zhHant, id };

export function siteCopy(lang: Lang) {
  const c = CATALOGUES[lang];
  return (key: SiteKey, vars?: Record<string, string | number>) =>
    c[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? `{${k}}`));
}
export type SiteT = ReturnType<typeof siteCopy>;
