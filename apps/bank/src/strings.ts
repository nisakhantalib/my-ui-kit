const CATALOGUES: Record<Lang, Record<StringKey, string>> = { en, 'zh-Hant': zhHant, id };

export function translator(lang: Lang) {
  const strings = CATALOGUES[lang];
  return (key: StringKey, vars: Record<string, string | number> = {}) =>
    strings[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export type T = ReturnType<typeof translator>;
